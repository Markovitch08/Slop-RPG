// Progression: XP rules (tier, level gap, repeat decay), level-ups, skill tree, shop, drops, skill panel.
module.exports = async ({ HM, step, log, assert, shot }) => {
  await HM('HM.PROG.reset()');
  assert(await HM('HM.SAVE.prog.level') === 1, 'reset gives level 1');
  assert(await HM('HM.player.maxMana') === 60, 'base max mana is 60');
  assert(await HM('HM.SAVE.weapons.join()') === 'rusty,dagger', 'fresh loadout is rusty sword + dagger');
  const b1 = await HM("HM.grantKillXP({type:'bandit',tier:1})");
  const k3 = await HM("HM.grantKillXP({type:'knight',tier:3})");
  log('xp: bandit t1 =', b1, ' knight t3 =', k3);
  assert(b1 === 20 && k3 > 5 * b1, 'tier-3 knight gives far more XP than tier-1 bandit (tier scaling)');
  await HM('HM.PROG.reset()');
  const xs = await HM("Array.from({length:20},()=>HM.grantKillXP({type:'bandit',tier:1}))");
  log('20 bandit kills:', xs.join(' '));
  assert(xs[0] === 20 && xs[8] === 10 && xs[16] === 5, 'repeat-kill decay x0.5 after 8, x0.25 after 16');
  assert(await HM('HM.SAVE.prog.level') > 1, 'level rises from bandit kills');
  assert(await HM('HM.player.maxHp') > 100, 'level-up raises max HP');
  await HM('HM.PROG.reset()');
  await HM('HM.SAVE.prog.level=20');
  const hi = await HM("HM.grantKillXP({type:'bandit',tier:1,boss:false})");
  const hiK = await HM("HM.grantKillXP({type:'knight',tier:1})");
  log('level-20 xp: bandit', hi, 'knight', hiK);
  assert(hi >= 1 && hi <= 4 && hiK <= 9, 'level-gap: level 20 gets >=1 and ~10% XP from tier 1');
  await HM('HM.PROG.reset()');
  await HM('HM.SAVE.prog.level=5');
  const g4 = await HM("HM.grantKillXP({type:'archer',tier:1})");
  assert(g4 === 14, 'level-gap: 3 levels above gives x0.4 (archer 35 -> 14)');
  await HM('HM.PROG.reset()');
  assert(await HM("HM.spellList().length") === 0, 'no spells on a fresh save');
  assert(await HM("HM.PROG.learn('S2')") === false, 'learning S2 without S1 is refused');
  assert(await HM("HM.PROG.learn('S1')") === true, 'learning S1 with 1 point succeeds');
  assert(await HM("HM.spellKnown('fire') && HM.spellList().includes('fire')"), 'S1 makes Fireball usable');
  assert(await HM("HM.player.maxMana") === 66, 'S1 gives +10% max mana');
  assert(await HM("HM.PROG.learn('V1')") === false, 'learning with no points is refused');
  assert((await HM("HM.buyWeapon('axe')")).ok === false, 'buyWeapon refuses without gold');
  await HM('HM.grantReward({gold:500,skillPoint:3})');
  assert((await HM("HM.buyWeapon('axe')")).ok === true && await HM("HM.SAVE.weapons.includes('axe')"), 'buyWeapon succeeds with gold');
  assert(await HM('HM.SAVE.prog.gold') === 100, 'gold deducted');
  assert((await HM("HM.buyWeapon('greatsword')")).ok === false, 'greatsword needs level 10');
  assert(await HM("HM.rollDrop({type:'brute',boss:'X'})") !== null, 'boss always drops an unowned weapon');
  assert(await HM("HM.rollDrop({type:'knight'},()=>0.5)") === null && await HM("['shield','longsword'].includes(HM.rollDrop({type:'knight'},()=>0.01))"), 'knight drop is rare (4%)');
  assert(await HM("HM.PROG.learn('V1') && HM.player.maxHp===120"), 'V1 adds 20 max HP');
  assert(await HM("HM.PROG.cost('fire')") === 25, 'fireball costs 25 mana');
  // a boss kill spawns a glowing granted weapon in the world
  const before = await HM('HM.weapons.length'), dBefore = await HM('HM.PROG.drops.length'), owned = await HM('HM.SAVE.weapons.length');
  await HM("HM.grantKillXP({type:'brute',boss:'Test',tier:2})");
  assert(await HM('HM.weapons.length') === before + 1 && await HM('HM.PROG.drops.length') === dBefore + 1 && await HM('HM.SAVE.weapons.length') === owned + 1, 'boss kill drops a granted weapon with a beam');
  await step(1);
  await HM('HM.openSkillPanel()');
  await step(0.2);
  assert(await HM('HM.skillPanel.mesh.visible') === true, 'skill panel opens');
  await shot('skilltree');
  await HM("HM.skillPanel.onClick('close')");
  assert(await HM('HM.skillPanel.mesh.visible') === false, 'skill panel closes');
  await step(1);
  await shot('wrist');
};
